function inferCountryCode(camera) {
  if (camera.countryCode) return camera.countryCode;
  if (/\bCanada\b|, CA$/i.test(camera.region)) return 'CA';
  if (/\bUS\b|\bUSA\b/i.test(camera.region)) return 'US';
  return null;
}

function inferCountryIsoNumeric(camera) {
  if (camera.countryIsoNumeric) return camera.countryIsoNumeric;
  const countryCode = inferCountryCode(camera);
  return countryCode === 'CA' ? '124' : countryCode === 'US' ? '840' : null;
}

